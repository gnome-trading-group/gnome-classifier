"""Polymarket International crypto markets written from fixed templates: the weekly price brackets on a Binance noon
candle (`bitcoin-price-on-november-3-2026`), up or down over an hourly Binance candle
(`bitcoin-up-or-down-october-29-2026-7pm-et`), and up or down over a 5- or 15-minute window on a Chainlink TWAP stream
(`eth-updown-15m-...`). The short windows compare the window's time-weighted average with the price at its start, a
different question from where the price ends (the average can sit above the start while the close is below it), so
they get their own measure and never match a close-versus-open market. The daily up or down markets are left to the
LLM: a tie there settles 50-50, so Down is not the negation of Up. So are the 4-hour ones.

Central bank rate decisions (`bank-of-england-decision`, `fomc`, ...) list one market per change bracket. A change
between brackets is rounded into one, and the rounding says what each bracket holds: under 25 bps counts as 25 and
the rest go to the nearest 25, ties away from 0 (most banks: "25 bps decrease" is any cut under 37.5), or the Fed's
rounding up to the next 25 ("25 bps decrease" is any cut up to 25).
"""
import re
from datetime import date, datetime, timedelta, timezone

from classifier.propositions.types import Comparator, Kind, Observation, Proposition, Stability
from classifier.propositions.venue.common import EASTERN, RATE_BANKS, number, price_rise, rate_decision

_ASSETS = {"bitcoin": "BTC", "btc": "BTC", "ethereum": "ETH", "eth": "ETH", "solana": "SOL", "sol": "SOL",
           "xrp": "XRP", "dogecoin": "DOGE", "doge": "DOGE", "hype": "HYPE", "bnb": "BNB"}
_SUBJECTS = {asset: f"{asset.lower()}-usd" for asset in set(_ASSETS.values())}

_BRACKETS_SLUG = re.compile(r"^(?P<asset>[a-z]+)-price-on-(?P<month>[a-z]+)-(?P<day>\d{1,2})-(?P<year>\d{4})$")
_SHORT_UPDOWN_SLUG = re.compile(r"^(?P<asset>[a-z]+)-updown-(?:5m|15m)-\d+$")
_HOURLY_UPDOWN_SLUG = re.compile(r"^(?P<asset>[a-z]+)-up-or-down-[a-z]+-\d{1,2}-\d{4}-\d{1,2}(?:am|pm)-et$")

_BRACKETS_RULE = re.compile(
    r'final "Close" price of the Binance 1 minute candle for (?P<pair>[A-Z]+)/USDT closing at 12:00 in the ET timezone '
    r"\(noon\) on the date specified in the title"
)
_HIGHER_BRACKET = "falls exactly between two brackets, then this market will resolve to the higher range bracket"
_CHAINLINK_TWAP_RULE = re.compile(
    r'resolve to "Up" if the time-weighted average price \(TWAP\) of [\w ]+?, generated by Chainlink, of the time range '
    r"specified in the title is greater than or equal to the price at the beginning of that range\..*?Chainlink, "
    r"specifically the (?P<pair>[A-Z]+)/USD TWAP data stream"
)
_BINANCE_HOURLY_RULE = re.compile(
    r'resolve to "Up" if the close price is greater than or equal to the open price for the (?P<pair>[A-Z]+)/USDT 1 hour '
    r"candle that begins on the time and date specified in the title"
)
_TITLE_WINDOW = re.compile(
    r"(?P<start>\d{1,2}(?::\d{2})?[AP]M)(?:-(?P<end>\d{1,2}(?::\d{2})?[AP]M))? ET$"
)
_RATE_SERIES = {
    "fomc": "fed", "ecb-interest-rates": "ecb", "bank-of-england-decision": "boe", "bank-of-canada-decision": "boc",
    "bank-of-brazil-decision": "bcb", "bank-of-mexico-decision": "banxico", "bank-of-israel-decision": "boi",
    "bank-of-korea-decision": "bok", "bank-of-russia-decision": "cbr", "central-bank-of-chile-decision": "bcch",
    "central-bank-of-colombia-decision": "banrep", "reserve-bank-of-australia-decision": "rba",
    "reserve-bank-of-india-decision": "rbi", "reserve-bank-of-new-zealand-decision": "rbnz",
    "swiss-national-bank-decision": "snb",
}
_RATE_BRACKET = re.compile(r"^(?P<bps>25|50\+) bps (?P<dir>decrease|cut|increase|hike)$", re.I)
_RATE_HOLD = re.compile(r"^no change$", re.I)
_NEAREST_ROUNDING = ("Increases or decreases of less than 25 bps will be rounded to 25 bps",
                     "rounded to the nearest 25 bps and will be rounded away from 0 in cases of equidistance")
_FED_ROUNDING = "the change will be rounded up to the nearest 25"
# The meeting's last day: "scheduled for December 8-9, 2026", "January 26 and January 27, 2027", "scheduled to
# conclude on April 28, 2027", "announced on December 4, 2026".
_MEETING = re.compile(
    r"(?:scheduled (?:for|to conclude on)|announced on) (?P<month>[A-Z][a-z]+) (?P<day>\d{1,2})"
    r"(?:(?:-| and (?:(?P<last_month>[A-Z][a-z]+) )?)(?P<last_day>\d{1,2}))?, (?P<year>\d{4})"
)
_BELOW = re.compile(r"^<\s?(?P<v>[\d,.]+)$")
_ABOVE = re.compile(r"^>\s?(?P<v>[\d,.]+)$")
_BETWEEN = re.compile(r"^(?P<low>[\d,.]+)\s?-\s?(?P<high>[\d,.]+)$")


def _slug(source: dict) -> str:
    return (source.get("event") or {}).get("slug") or ""


def _family(slug: str) -> tuple[str, re.Match] | None:
    for name, pattern in (("brackets", _BRACKETS_SLUG), ("short", _SHORT_UPDOWN_SLUG), ("hourly", _HOURLY_UPDOWN_SLUG)):
        if (m := pattern.match(slug)) and m.group("asset") in _ASSETS:
            return name, m
    return None


def _rate_series(source: dict) -> str | None:
    return _RATE_SERIES.get((source.get("event") or {}).get("seriesSlug") or "")


def claims(source: dict) -> bool:
    return _family(_slug(source)) is not None or _rate_series(source) is not None


def is_no_side(source: dict) -> bool:
    return source.get("outcome") in ("No", "Down")


def _utc(text: str | None) -> datetime | None:
    if not text:
        return None
    return datetime.fromisoformat(text.replace("Z", "+00:00")).astimezone(timezone.utc)


def _is_eastern_clock(at: datetime, clock: str | None) -> bool:
    """Whether `at` reads `clock` ("7PM", "10:45AM") on an Eastern wall clock."""
    if clock is None:
        return False
    fmt = "%I:%M%p" if ":" in clock else "%I%p"
    wanted = datetime.strptime(clock, fmt)
    local = at.astimezone(EASTERN)
    return (local.hour, local.minute) == (wanted.hour, wanted.minute)


def _bracket(label: str) -> dict | None:
    """A bracket label as proposition fields. A price exactly on a boundary belongs to the higher bracket."""
    if m := _BELOW.match(label):
        return {"kind": Kind.THRESHOLD, "comparator": Comparator.LT, "value": number(m.group("v"))}
    if m := _ABOVE.match(label):
        return {"kind": Kind.THRESHOLD, "comparator": Comparator.GTE, "value": number(m.group("v"))}
    if m := _BETWEEN.match(label):
        return {"kind": Kind.RANGE, "low": number(m.group("low")), "high": number(m.group("high")), "high_inclusive": False}
    return None


def _rate_bracket(label: str, rules: str) -> dict | None:
    if _RATE_HOLD.match(label):
        return {"kind": Kind.RANGE, "low": 0.0, "high": 0.0}
    m = _RATE_BRACKET.match(label)
    if m is None:
        return None
    if _FED_ROUNDING in rules:
        edge = 25.0
    elif all(phrase in rules for phrase in _NEAREST_ROUNDING):
        edge = 37.5
    else:
        return None
    cut = m.group("dir").lower() in ("decrease", "cut")
    if m.group("bps") == "25":
        # The 25 bracket holds every change from just past 0 to the edge; the Fed's includes 25 itself, the nearest-25
        # rounding's stops short of 37.5 (which rounds away, to 50).
        closed = edge == 25.0
        if cut:
            return {"kind": Kind.RANGE, "low": -edge, "high": 0.0, "low_inclusive": closed, "high_inclusive": False}
        return {"kind": Kind.RANGE, "low": 0.0, "high": edge, "low_inclusive": False, "high_inclusive": closed}
    beyond = {(True, 25.0): Comparator.LT, (True, 37.5): Comparator.LTE, (False, 25.0): Comparator.GT,
              (False, 37.5): Comparator.GTE}[(cut, edge)]
    return {"kind": Kind.THRESHOLD, "comparator": beyond, "value": -edge if cut else edge}


def _rate_meeting(rules: str, slug: str) -> date | None:
    m = _MEETING.search(rules)
    if m is None:
        return None
    month = m.group("last_month") or m.group("month")
    # The event's slug names the meeting's month ("...-decision-in-december-2026"); a date in another month is some
    # other day the rules mention.
    if m.group("month").lower() not in slug:
        return None
    day = m.group("last_day") or m.group("day")
    try:
        return datetime.strptime(f"{month} {day} {m.group('year')}", "%B %d %Y").date()
    except ValueError:
        return None


def _rate_decision(bank: str, source: dict) -> Proposition | None:
    market = source.get("market") or {}
    rules = re.sub(r"\s+", " ", market.get("description") or "")
    fields = _rate_bracket((market.get("groupItemTitle") or source.get("outcome") or "").strip(), rules)
    meeting = _rate_meeting(rules, _slug(source))
    if fields is None or meeting is None:
        return None
    return rate_decision(RATE_BANKS[bank], meeting, fields)


def read(source: dict) -> Proposition | None:
    if bank := _rate_series(source):
        return _rate_decision(bank, source)
    found = _family(_slug(source))
    if found is None:
        return None
    name, slug = found
    asset = _ASSETS[slug.group("asset")]
    market = source.get("market") or {}
    rules = re.sub(r"\s+", " ", market.get("description") or "")
    subject = _SUBJECTS[asset]

    if name == "brackets":
        m = _BRACKETS_RULE.search(rules)
        fields = _bracket(market.get("groupItemTitle") or source.get("outcome") or "")
        if m is None or m.group("pair") != asset or _HIGHER_BRACKET not in rules or fields is None:
            return None
        noon = datetime.strptime(f"{slug.group('month')} {slug.group('day')} {slug.group('year')} 12", "%B %d %Y %H")
        return Proposition(
            subject=subject, measure="price", unit="usd", observation=Observation.AT_TIME,
            window_end=noon.replace(tzinfo=EASTERN).astimezone(timezone.utc), stability=Stability.LIVE,
            resolution_source=f"binance-{asset.lower()}usdt-1m-close", **fields,
        )

    # The window is in the title in Eastern time; the market's own start and end times must say the same.
    start, end = _utc(market.get("eventStartTime")), _utc(market.get("endDate"))
    window = _TITLE_WINDOW.search((source.get("event") or {}).get("title") or "")
    if start is None or window is None or not _is_eastern_clock(start, window.group("start")):
        return None
    if name == "hourly":
        m = _BINANCE_HOURLY_RULE.search(rules)
        if m is None or m.group("pair") != asset or window.group("end"):
            return None
        return price_rise(subject, start, start + timedelta(hours=1), f"binance-{asset.lower()}usdt-1h-candle")
    m = _CHAINLINK_TWAP_RULE.search(rules)
    if m is None or m.group("pair") != asset or end is None or not _is_eastern_clock(end, window.group("end")):
        return None
    return Proposition(
        subject=subject, kind=Kind.THRESHOLD, measure="twap_change", unit="usd", comparator=Comparator.GTE, value=0.0,
        observation=Observation.AT_TIME, window_start=start, window_end=end, stability=Stability.LIVE,
        resolution_source=f"chainlink-{asset.lower()}usd-twap-stream",
    )
